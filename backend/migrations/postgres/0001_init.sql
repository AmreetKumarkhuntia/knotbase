-- The schema of migrations/sqlite/0001_init.sql in Postgres types. Timestamps stay ISO-8601 text in the format SQLite
-- writes, so the row structs are one set of types for both engines.
CREATE TABLE node (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  parent_id  BIGINT REFERENCES node(id) ON DELETE CASCADE,
  name       TEXT NOT NULL CHECK (trim(name) <> ''),
  kind       TEXT NOT NULL CHECK (trim(kind) <> ''),
  doc        TEXT NOT NULL DEFAULT '',
  x          DOUBLE PRECISION NOT NULL DEFAULT 0,
  y          DOUBLE PRECISION NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'),
  updated_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'),
  CHECK (parent_id IS NOT NULL OR id = 1),
  UNIQUE (parent_id, id)  -- parent key for edge's pair FKs
);
CREATE TABLE edge (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  parent_id  BIGINT NOT NULL,
  source_id  BIGINT NOT NULL,
  target_id  BIGINT NOT NULL,
  label      TEXT NOT NULL DEFAULT '',
  created_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'),
  updated_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'),
  CHECK (source_id <> target_id),
  -- pair FKs: endpoints must exist AND be children of parent_id, i.e. siblings
  FOREIGN KEY (parent_id, source_id) REFERENCES node(parent_id, id) ON DELETE CASCADE,
  FOREIGN KEY (parent_id, target_id) REFERENCES node(parent_id, id) ON DELETE CASCADE
);
CREATE TABLE item (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  node_id    BIGINT NOT NULL REFERENCES node(id) ON DELETE CASCADE,
  text       TEXT NOT NULL CHECK (trim(text) <> ''),
  done       BOOLEAN NOT NULL DEFAULT false,
  created_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'),
  updated_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')
);
